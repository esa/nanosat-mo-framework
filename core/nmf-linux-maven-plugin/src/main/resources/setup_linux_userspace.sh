#!/bin/sh
cd ${0%/*}

###############################################################################
# Variables:
user_nmf_admin="nmf-admin"
user_nmf_app_prefix="app-"
group_nmf_apps="nmf-apps"
start_script_name="start_supervisor.sh"
dir_nmf=$(pwd -P)/
dir_home="/home/"
###############################################################################

###############################################################################
# The commands that create and delete users and groups differ between a full
# Linux distribution and BusyBox. The distribution is detected here rather than
# declared, because the same mission is deployed to both: the NMF makes the same
# check when it creates the user of an App (see LinuxUsersGroups.adduser).
###############################################################################
if adduser --help 2>&1 | grep -q "BusyBox"; then
	is_busybox="true"
	shell_nmf_admin="/bin/sh"
else
	is_busybox="false"
	shell_nmf_admin="/bin/bash"
fi

# nmf_deluser <user> - deletes the user and its home directory. The home
# directory is removed separately: BusyBox has no option for it, and the Debian
# option needs the full perl package, which slim images do not have.
nmf_deluser() {
	deluser "$1" && rm -rf "$dir_home$1"
}

# nmf_adduser <user> - adds a system user with a group of its own. BusyBox
# creates the group in a separate command.
nmf_adduser() {
	if [ "$is_busybox" = "true" ]; then
		addgroup -S "$1"
		adduser -S -s "$shell_nmf_admin" -G "$1" "$1"
	else
		adduser --system --home "$dir_home$1" --shell "$shell_nmf_admin" --group "$1"
	fi
}

# nmf_addgroup <group> - adds a group.
nmf_addgroup() {
	if [ "$is_busybox" = "true" ]; then
		addgroup "$1"
	else
		groupadd "$1"
	fi
}

# The script must be run as root
if [ $(whoami) != 'root' ]; then
	echo "The current user is: $(whoami)"
	echo "Please run this script as root or with sudo!"
	exit 1
fi

# Check if the NMF Admin User exists
if id -u "$user_nmf_admin" >/dev/null 2>&1; then
    echo "The user $user_nmf_admin already exists! Let's delete it and create again..."
	nmf_deluser $user_nmf_admin
	RESULT=$?

	if [ $RESULT -eq 0 ]; then
	  echo "The user $user_nmf_admin was successfully deleted!"
	else
	  echo "ERROR!!! The user $user_nmf_admin could not be deleted!"
	  echo "Please close any open sessions with the $user_nmf_admin user and try again!"
	  exit 1
	fi
fi

# Add the NMF Admin User. The account has no password and is locked, so
# nobody can log in as it: the Supervisor is started as this user by root.
nmf_adduser $user_nmf_admin
passwd -l $user_nmf_admin

###############################################################################
# The Supervisor (nmf-admin) needs root for a few operations on the accounts of
# the Apps. It is not given the generic commands (adduser, deluser, chgrp,
# chmod), which accept any argument and so would give it root. Instead, it may
# run, as root, only:
#   1. The NMF App account helper, installed below as a root-owned file, which
#      accepts nothing but the account of an App (app-<name>) and that App's
#      own directories in the NMF.
#   2. su - app-<name>, to start an App as its own user.
###############################################################################
helper_path="/usr/local/sbin/nmf-app-account"
mkdir -p "${helper_path%/*}"
{
echo '#!/bin/sh'
echo "dir_nmf=\"$dir_nmf\""
cat <<'HELPER'
# nmf-app-account - the only operations that the NMF Supervisor may run as root.
# Generated by setup_linux_userspace.sh, owned by root and not writable by the
# Supervisor. Usage:
#   nmf-app-account create <user>        - adds the account of an App
#   nmf-app-account delete <user>        - deletes the account of an App
#   nmf-app-account own <user> <dir>     - gives an App's directory to its group
# <user> must be app-<name>, with the same name rule as an NMF package.
set -eu

fail() {
	echo "nmf-app-account: $1" >&2
	exit 1
}

nl='
'
check_user() {
	case "$1" in
		*"$nl"*) fail "invalid App user" ;;
	esac
	printf '%s' "$1" | grep -Eqx 'app-[A-Za-z0-9][A-Za-z0-9._+-]{0,127}' \
		|| fail "not the user of an App: $1"
}

home_of() {
	awk -F: -v u="$1" '$1 == u { print $6 }' /etc/passwd
}

is_busybox() {
	adduser --help 2>&1 | grep -q "BusyBox"
}

[ $# -ge 2 ] || fail "usage: nmf-app-account create|delete|own <user> [<dir>]"
command=$1
user=$2
check_user "$user"
app=${user#app-}

case "$command" in
create)
	if is_busybox; then
		addgroup -S "$user"
		adduser -s /bin/bash -G "$user" -S "$user"
	else
		adduser --system --home "/home/$user" --shell /bin/bash --group "$user"
	fi
	# The home directory belongs to the App, and to the Supervisor's group.
	home=$(home_of "$user")
	if [ "$home" = "/home/$user" ] && [ -d "$home" ] && [ ! -L "$home" ]; then
		chgrp -hR nmf-admin "$home"
		chmod -R 770 "$home"
	fi
	;;
delete)
	[ -n "$(home_of "$user")" ] || fail "no such user: $user"
	deluser "$user"
	rm -rf "/home/$user"
	;;
own)
	[ $# -eq 3 ] || fail "usage: nmf-app-account own <user> <dir>"
	[ -n "$(home_of "$user")" ] || fail "no such user: $user"
	# Only the App's own directories. The apps and logs directories may be
	# links set up by the mission, so only the files that the Supervisor or the
	# App itself own are given to the App's group, and links are not followed.
	case "$3" in
		"${dir_nmf}apps/$app" | "${dir_nmf}logs/app_$app") ;;
		*) fail "not a directory of the App $app: $3" ;;
	esac
	[ -d "$3" ] && [ ! -L "$3" ] || fail "not a directory: $3"
	cd "$3"
	find . \( -user nmf-admin -o -user "$user" \) -exec chgrp -h "$user" {} +
	;;
*)
	fail "unknown command: $command"
	;;
esac
HELPER
} > "$helper_path"
chown root:root "$helper_path"
chmod 755 "$helper_path"

rules_path="/etc/sudoers.d/$user_nmf_admin"
rules_all="#
# This file was generated during the installation of the NanoSat MO Framework.
#
$user_nmf_admin ALL=(root) NOPASSWD: $helper_path
$user_nmf_admin ALL=(root) NOPASSWD: /bin/su - $user_nmf_app_prefix*
"

echo "$rules_all" > $rules_path
chmod 440 $rules_path

# Add NMF App Group:
nmf_addgroup $group_nmf_apps

# Function to create a directory with: owner + group + permissions
create_dir(){
    permissions=$1
    owner=$2
    group=$3
    directory=$4

	mkdir $directory
	chown -R $owner:$group $directory
	chmod -R $permissions $directory
}

chown -R $user_nmf_admin:$user_nmf_admin .
chmod 775 .
chown $user_nmf_admin:$user_nmf_admin $start_script_name
chmod 700 $start_script_name

create_dir 775 $user_nmf_admin $user_nmf_admin apps
create_dir 775 $user_nmf_admin $user_nmf_admin jars-mission
create_dir 775 $user_nmf_admin $user_nmf_admin jars-nmf
create_dir 775 $user_nmf_admin $user_nmf_admin libs
create_dir 700 $user_nmf_admin $user_nmf_admin packages
create_dir 770 $user_nmf_admin $group_nmf_apps public_square
create_dir 700 $user_nmf_admin $user_nmf_admin nmf_updates

###############################################################################
# Lock the bootloader domain (baseline files + runtime state):
#   - The directory is only accessible to the NMF Admin; the NMF Apps are
#     locked out of it (the baseline files decide what code runs at boot).
#   - The factory baseline file is immutable in flight: owned by root and
#     read-only, beyond the reach of in-flight software maintenance.
###############################################################################
chown -R $user_nmf_admin:$user_nmf_admin bootloader
chmod 700 bootloader
chown root:root bootloader/baseline-factory.properties
chmod 444 bootloader/baseline-factory.properties

echo "Success! The NanoSat MO Framework was set up for linux-userspace isolation!"

